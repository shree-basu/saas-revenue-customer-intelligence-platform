-- STATIC REFERENCE ONLY. Do not execute. Requires separately approved monitoring access.
-- Query-history samples are illustrative; no Snowflake account was queried.
SELECT QUERY_ID, QUERY_TAG, WAREHOUSE_NAME, TOTAL_ELAPSED_TIME,
       BYTES_SCANNED, PARTITIONS_SCANNED, PARTITIONS_TOTAL,
       QUEUED_OVERLOAD_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
  AND QUERY_TAG LIKE 'saas_example:%'
ORDER BY START_TIME DESC
LIMIT 100;

-- Compute attribution excludes warehouse idle time and other service/storage costs.
SELECT WAREHOUSE_NAME, SUM(CREDITS_ATTRIBUTED_COMPUTE) AS QUERY_COMPUTE_CREDITS
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY
WHERE START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
GROUP BY WAREHOUSE_NAME;
