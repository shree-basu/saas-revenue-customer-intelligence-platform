-- STATIC REFERENCE ONLY. Do not execute. Illustrative names are not real account IDs.
-- A security administrator must review ownership, grants and managed access first.
CREATE DATABASE IF NOT EXISTS SAAS_EXAMPLE_DB;
CREATE SCHEMA IF NOT EXISTS SAAS_EXAMPLE_DB.RAW WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SAAS_EXAMPLE_DB.STAGING WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SAAS_EXAMPLE_DB.CORE WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS SAAS_EXAMPLE_DB.MARTS WITH MANAGED ACCESS;

CREATE ROLE IF NOT EXISTS SAAS_EXAMPLE_DBT_ROLE;
CREATE ROLE IF NOT EXISTS SAAS_EXAMPLE_FABRIC_READER_ROLE;

GRANT USAGE ON DATABASE SAAS_EXAMPLE_DB TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT USAGE ON SCHEMA SAAS_EXAMPLE_DB.RAW TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT USAGE ON SCHEMA SAAS_EXAMPLE_DB.STAGING TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT USAGE ON SCHEMA SAAS_EXAMPLE_DB.CORE TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT USAGE ON SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT USAGE ON WAREHOUSE SAAS_EXAMPLE_TRANSFORM_WH TO ROLE SAAS_EXAMPLE_DBT_ROLE;

GRANT SELECT ON ALL TABLES IN SCHEMA SAAS_EXAMPLE_DB.RAW TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SAAS_EXAMPLE_DB.RAW TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA SAAS_EXAMPLE_DB.STAGING TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA SAAS_EXAMPLE_DB.CORE TO ROLE SAAS_EXAMPLE_DBT_ROLE;
GRANT CREATE TABLE, CREATE VIEW ON SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_DBT_ROLE;

-- The future Fabric boundary can read certified MARTS only, never RAW or STAGING.
GRANT USAGE ON DATABASE SAAS_EXAMPLE_DB TO ROLE SAAS_EXAMPLE_FABRIC_READER_ROLE;
GRANT USAGE ON SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_FABRIC_READER_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_FABRIC_READER_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_FABRIC_READER_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_FABRIC_READER_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA SAAS_EXAMPLE_DB.MARTS TO ROLE SAAS_EXAMPLE_FABRIC_READER_ROLE;
